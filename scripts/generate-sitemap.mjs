#!/usr/bin/env node
/**
 * Builds public/sitemap.xml from INDEXABLE_PUBLIC_ROUTES in src/lib/seoRoutes.ts.
 *
 *   node scripts/generate-sitemap.mjs          write public/sitemap.xml
 *   node scripts/generate-sitemap.mjs --check  fail if the file is out of date
 *   node scripts/generate-sitemap.mjs --from-git  trust git dates in a deepened clone
 *
 * <lastmod> is the date of the last git commit that touched the page's source
 * folder. Without full git history (a shallow clone or an export with no
 * .git), dates cannot be trusted, so each route keeps the <lastmod> already in
 * public/sitemap.xml and only new routes get today's date.
 *
 * Canonical origin: VITE_PUBLIC_SITE_URL, falling back to https://vowora.uk.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const SITEMAP = resolve(root, 'public/sitemap.xml');
const ROUTES_FILE = resolve(root, 'src/lib/seoRoutes.ts');
const origin = (process.env.VITE_PUBLIC_SITE_URL || 'https://vowora.uk').trim().replace(/\/+$/, '');
const check = process.argv.includes('--check');
// After `git fetch --depth=N` a clone is still flagged shallow even when it
// holds every commit; --from-git trusts its dates anyway.
const forceGit = process.argv.includes('--from-git');

// ── Routes from the single source of truth ──
const source = readFileSync(ROUTES_FILE, 'utf8');
const block = source.slice(source.indexOf('INDEXABLE_PUBLIC_ROUTES'), source.indexOf('];', source.indexOf('INDEXABLE_PUBLIC_ROUTES')));
const routes = [...block.matchAll(/\{\s*path:\s*'([^']+)'[^}]*changeFrequency:\s*'([a-z]+)'[^}]*priority:\s*([0-9.]+)/g)].map(
  ([, path, changeFrequency, priority]) => ({ path, changeFrequency, priority: Number(priority) }),
);
if (routes.length === 0) throw new Error('No INDEXABLE_PUBLIC_ROUTES found in src/lib/seoRoutes.ts');

// ── Dates ──
function git(args) {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
}
const fullHistory = forceGit || git(['rev-parse', '--is-shallow-repository']) === 'false';

const existing = new Map();
if (existsSync(SITEMAP)) {
  for (const m of readFileSync(SITEMAP, 'utf8').matchAll(/<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)) {
    existing.set(new URL(m[1]).pathname.replace(/\/+$/, '') || '/', m[2]);
  }
}

function pageFolder(path) {
  return path === '/' ? 'src/pages/home' : `src/pages${path}`;
}

const today = new Date().toISOString().slice(0, 10);
function lastmodFor(path) {
  if (fullHistory) {
    const date = git(['log', '-1', '--format=%cs', '--', pageFolder(path)]);
    if (/^\d{4}-\d{2}-\d{2}$/.test(date)) return date;
  }
  return existing.get(path) || today;
}

// ── Output ──
const loc = (path) => (path === '/' ? `${origin}/` : `${origin}${path}`);
const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by scripts/generate-sitemap.mjs from INDEXABLE_PUBLIC_ROUTES. Do not edit by hand. -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...routes.map((r) =>
    [
      '  <url>',
      `    <loc>${loc(r.path)}</loc>`,
      `    <lastmod>${lastmodFor(r.path)}</lastmod>`,
      `    <changefreq>${r.changeFrequency}</changefreq>`,
      `    <priority>${r.priority.toFixed(1)}</priority>`,
      '  </url>',
    ].join('\n'),
  ),
  '</urlset>',
  '',
].join('\n');

if (check) {
  const current = existsSync(SITEMAP) ? readFileSync(SITEMAP, 'utf8') : '';
  const locs = (text) => [...text.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]).join('\n');
  if (locs(current) !== locs(xml)) {
    console.error('public/sitemap.xml does not match INDEXABLE_PUBLIC_ROUTES. Run: npm run seo:sitemap');
    process.exit(1);
  }
  console.log(`Sitemap is up to date (${routes.length} URLs).`);
} else {
  writeFileSync(SITEMAP, xml);
  console.log(`Wrote public/sitemap.xml (${routes.length} URLs, ${fullHistory ? 'dates from git history' : 'existing dates kept: no full git history'}).`);
}
